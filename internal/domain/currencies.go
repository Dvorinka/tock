var currencyByCode = func() map[string]currencyInfo {
	m := make(map[string]currencyInfo, len(currencies))
	for _, c := range currencies {
		m[c.Code] = c
	}
	return m
}()

// CurrencySymbol returns the display symbol for an ISO 4217 code
// (the code itself when no symbol is known), like CurrencyService::getCurrencySymbol.
func CurrencySymbol(code string) string {
	if c, ok := currencyByCode[code]; ok {
		return c.Symbol
	}
	return code
}

// ValidCurrency reports whether code is a known ISO 4217 currency (CurrencyRule).
func ValidCurrency(code string) bool {
	_, ok := currencyByCode[code]
	return ok
}

// CurrencyList is the GET /api/v1/currencies payload.
func CurrencyList() []currencyInfo { return currencies }
